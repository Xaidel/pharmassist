/**
 * Draw Naga City's boundary as a dashed line, so people can see where the
 * city ends. Call once the map style has loaded.
 */
export function addNagaBoundary(map: MapLibreMap): void {
  if (map.getSource(SOURCE_ID) !== undefined) {
    return
  }
  map.addSource(SOURCE_ID, {
    type: 'geojson',
    data: {
      type: 'Feature',
      properties: { name: 'Naga City' },
      geometry: { type: 'Polygon', coordinates: [NAGA_CITY_RING] },
    },
  })
  map.addLayer({
    id: LAYER_ID,
    type: 'line',
    source: SOURCE_ID,
    layout: { 'line-join': 'round', 'line-cap': 'round' },
    paint: {
      'line-color': LINE_COLOR,
      'line-width': 2,
      'line-opacity': 0.6,
      'line-dasharray': [3, 2],
    },
  })
}
